"""Generate per-chromosome eval configs for a genome-wide model at one epoch.

Usage: python scripts/make_eval_configs.py <template.yaml> <runId> <epoch> [suffix]
Writes configs/test_{runId}_chr{C}{suffix}.yaml for C in 1..22 and prints the
`ln -sf` commands needed for the per-chromosome checkpoint symlinks.
"""
import os
import re
import sys

if len(sys.argv) < 4:
    sys.exit(__doc__)
template, run_id, epoch = sys.argv[1], sys.argv[2], sys.argv[3]
suffix = sys.argv[4] if len(sys.argv) > 4 else ""

src = open(template).read()
fields = dict(re.findall(r"^(\w+):\s*(.+?)\s*$", src, re.M))
dataset = fields.get("dataset", "1KGP")
pop = fields.get("population", "ALL")
seg, ov = fields.get("segLen", "1024"), fields.get("overlap", "128")
base_chr = fields.get("chromosome", "22")

for c in range(1, 23):
    out = src
    out = re.sub(r"^runId:.*$", f"runId: {run_id}", out, flags=re.M)
    out = re.sub(r"^chromosome:.*$", f"chromosome: {c}", out, flags=re.M)
    out = re.sub(r"^chromosomes:.*$", f"chromosomes: [{c}]", out, flags=re.M)
    out = re.sub(r"^epoch:.*$", f"epoch: {epoch}", out, flags=re.M)
    path = f"configs/test_{run_id}_chr{c}{suffix}.yaml"
    with open(path, "w") as f:
        f.write(f"# Eval of genome-wide {run_id} at epoch {epoch}, chromosome {c}.\n"
                f"# Generated by scripts/make_eval_configs.py from {os.path.basename(template)}.\n")
        f.write(out)

print(f"wrote 22 configs: configs/test_{run_id}_chr{{1..22}}{suffix}.yaml")
print("\n# checkpoint symlinks (run in checkpoints/ on the cluster):")
print(f'for C in $(seq 1 22); do [ "$C" = "{base_chr}" ] && continue; '
      f'ln -sf checkpoint_{run_id}_{dataset}_chr{base_chr}_{pop}_seg{seg}_overlap{ov}_epoch_{epoch}.pth '
      f'checkpoint_{run_id}_{dataset}_chr${{C}}_{pop}_seg{seg}_overlap{ov}_epoch_{epoch}.pth; done')
